/** The game content's English by key, as data.ts registers it through tc() when it loads: for the full game, and for
 *  the demo (data.ts loaded with __DEMO__ set, as the demo build sees it). Each is read in a fresh Node process. */
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

function collect(demo: boolean): { entries: Map<string, string>; conflicts: string[] } {
  const url = (file: string) => pathToFileURL(file).href;
  const script = `globalThis.__DEMO__ = ${demo};
    const { CONTENT_SOURCE, CONTENT_CONFLICTS } = await import(${JSON.stringify(url('src/i18n/index.ts'))});
    await import(${JSON.stringify(url('src/game/data.ts'))});
    process.stdout.write(JSON.stringify({ entries: [...CONTENT_SOURCE], conflicts: [...CONTENT_CONFLICTS] }));`;
  const out = execFileSync(process.execPath, ['--no-warnings', '--input-type=module', '-e', script], { encoding: 'utf8', maxBuffer: 64 << 20 });
  const parsed = JSON.parse(out) as { entries: [string, string][]; conflicts: string[] };
  return { entries: new Map(parsed.entries), conflicts: parsed.conflicts };
}

let cached: { full: Map<string, string>; demo: Map<string, string>; conflicts: string[] } | null = null;

export function contentSource() {
  if (!cached) {
    const full = collect(false);
    cached = { full: full.entries, demo: collect(true).entries, conflicts: full.conflicts };
  }
  return cached;
}

/** src/i18n/en/content.ts as it should read. */
export function contentFileText(): string {
  const entries = [...contentSource().full.entries()].sort(([a], [b]) => a.localeCompare(b, 'en'));
  const lines = entries.map(([key, english]) => `  ${JSON.stringify(key)}: ${JSON.stringify(english)},`);
  return `// Generated by \`npm run i18n:content\` from the game data (src/game/data.ts). Don't edit: change the data and run it again.\nexport const CONTENT = {\n${lines.join('\n')}${lines.length ? '\n' : ''}};\n`;
}

/** Content keys the demo may carry: there in its data with the same English (the Runesmith's "???" is not his name). */
export function demoContentKeys(): Set<string> {
  const { full, demo } = contentSource();
  return new Set([...demo].filter(([key, english]) => full.get(key) === english).map(([key]) => key));
}
